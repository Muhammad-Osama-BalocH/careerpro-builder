import { NextRequest, NextResponse } from 'next/server';
import { timingSafeEqual } from 'crypto';
import { adminDb } from '@/lib/firebase-admin'; // Assume admin SDK exists

function clearOAuthCookie(response: NextResponse) {
  response.cookies.set('github_oauth_state', '', {
    httpOnly: true,
    secure: process.env.NODE_ENV === 'production',
    sameSite: 'lax',
    path: '/',
    maxAge: 0,
  });
}

export async function GET(request: NextRequest) {
  const { searchParams } = new URL(request.url);
  const code = searchParams.get('code');
  const returnedState = searchParams.get('state');

  // 1. Read and validate the OAuth state cookie
  const cookieValue = request.cookies.get('github_oauth_state')?.value;

  const redirectError = new URL('/career?error=auth_failed', request.url);

  if (!code || !returnedState || !cookieValue) {
    const response = NextResponse.redirect(redirectError);
    clearOAuthCookie(response);
    return response;
  }

  // Cookie format: "nonce:uid"
  const colonIndex = cookieValue.indexOf(':');
  if (colonIndex === -1) {
    const response = NextResponse.redirect(redirectError);
    clearOAuthCookie(response);
    return response;
  }

  const expectedNonce = cookieValue.substring(0, colonIndex);
  const userId = cookieValue.substring(colonIndex + 1);

  // 2. Constant-time comparison of the nonce
  //    Both values are UUIDs (36 chars) generated by crypto.randomUUID()
  if (expectedNonce.length !== returnedState.length) {
    const response = NextResponse.redirect(redirectError);
    clearOAuthCookie(response);
    return response;
  }

  const nonceMatch = timingSafeEqual(
    Buffer.from(expectedNonce, 'utf-8'),
    Buffer.from(returnedState, 'utf-8'),
  );

  if (!nonceMatch) {
    const response = NextResponse.redirect(redirectError);
    clearOAuthCookie(response);
    return response;
  }

  if (!userId) {
    const response = NextResponse.redirect(redirectError);
    clearOAuthCookie(response);
    return response;
  }

  try {
    // 3. Exchange code for access token (SERVER SIDE ONLY)
    const tokenResponse = await fetch('https://github.com/login/oauth/access_token', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/x-www-form-urlencoded',
        'Accept': 'application/json',
      },
      body: new URLSearchParams({
        client_id: process.env.NEXT_PUBLIC_GITHUB_CLIENT_ID!,
        client_secret: process.env.GITHUB_CLIENT_SECRET!,
        code,
      }).toString(),
    });

    const tokenData = await tokenResponse.json();
    if (tokenData.error) throw new Error(tokenData.error);

    // 4. Fetch GitHub User (SERVER SIDE ONLY)
    const userResponse = await fetch('https://api.github.com/user', {
      headers: {
        'Authorization': `token ${tokenData.access_token}`,
        'Accept': 'application/json',
      },
    });

    const githubUser = await userResponse.json();

    // 5. Update Firestore (SERVER SIDE ONLY)

    // 5a. Store token securely in githubTokens collection
    await adminDb.collection('githubTokens').doc(userId).set({
      accessToken: tokenData.access_token,
      updatedAt: new Date().toISOString(),
    });

    // 5b. Update profile with connection info
    const profileRef = adminDb.collection('careerProfiles').where('userId', '==', userId);
    const snapshot = await profileRef.get();

    if (!snapshot.empty) {
      const doc = snapshot.docs[0];
      await doc.ref.update({
        githubConnection: {
          isConnected: true,
          username: githubUser.login,
          githubId: String(githubUser.id),
        },
      });
    } else {
      // Create a minimal career profile so the GitHub connection info is not lost
      await adminDb.collection('careerProfiles').add({
        userId,
        isPublic: true,
        professionalTitle: '',
        careerSummary: '',
        careerInterests: [],
        githubUrl: githubUser.html_url ?? '',
        linkedinUrl: '',
        certifications: [],
        achievements: [],
        languages: [],
        targetRoles: [],
        githubConnection: {
          isConnected: true,
          username: githubUser.login,
          githubId: String(githubUser.id),
        },
        createdAt: new Date().toISOString(),
        updatedAt: new Date().toISOString(),
      });
    }

    const response = NextResponse.redirect(new URL('/career?success=github_connected', request.url));
    clearOAuthCookie(response);
    return response;
  } catch (error) {
    console.error('GitHub OAuth Detailed Error:', error);
    const response = NextResponse.redirect(new URL('/career?error=auth_failed', request.url));
    clearOAuthCookie(response);
    return response;
  }
}
